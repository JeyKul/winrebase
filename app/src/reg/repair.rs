const STATE_VALUES: &[(&str, &str)] = &[
    (r"currentcontrolset\control\session manager", "setupexecute"),
    (r"currentcontrolset\control\pnp", "disablelkg"),
    (r"currentcontrolset\services\i8042prt\parameters", "layerdriver jpn"),
    (r"currentcontrolset\services\i8042prt\parameters", "layerdriver kor"),
    (r"\microsoft\windows nt\currentversion\fontlink", "updatefontlinks"),
    (r"\wow6432node\microsoft\windows\currentversion\uninstall\microsoft edge", "noremove"),
    (r"\microsoft\windows nt\currentversion\image file execution options\microsoftedgeupdate.exe", "disableexceptionchainvalidation"),
];

/// State databases that are restored from the WIM when more than half of them is gone.
const RESTORABLE_STATE: &[&str] = &[
    r"\microsoft\windows\currentversion\sidebyside",
    r"\microsoft\windows\currentversion\component based servicing",
    r"\microsoft\windows\currentversion\appx\appxalluserstore",
    r"\microsoft\windows\currentversion\capabilityaccessmanager\capabilities",
];
const STATE_LOSS: f64 = 0.5;
const CBS_PACKAGES: &str = r"\microsoft\windows\currentversion\component based servicing\packages";

/// Regenerated by PnP; stale free-cell copies there stopped the kernel with 0x69.
const NO_UNDELETE: &[&str] = &[r"\control\deviceclasses\", r"\control\devicecontainers\"];

const DRIVER_PROPS: &str = "{a8b865dd-2e3d-4094-ad97-e593a70c75d6}";
const REINSTALL_CLASSES: &[&str] = &["{4d36e972-e325-11ce-bfc1-08002be10318}"]; // Net
const CONFIGFLAG_REINSTALL: u32 = 0x20;

fn is_state(path: &str, value: Option<&str>) -> bool {
    let p = lower(path);
    if STATE_KEYS.iter().any(|k| p == *k || p.starts_with(&format!("{k}\\"))) {
        return true;
    }
    value.map(|v| {
        let v = lower(v);
        STATE_VALUES.iter().any(|(k, n)| p == *k && v == *n)
            // perflib rewrites counter blocks of registered providers itself
            || (v == "counterblock" && p.starts_with(r"\microsoft\windows nt\currentversion\perflib\_v2providers\"))
    }).unwrap_or(false)
}

/// WIM hives use X: as the system drive placeholder; Setup rewrites it.
fn fix_name(name: &str, drive: &str) -> String {
    if name.get(..2).map(|p| p.eq_ignore_ascii_case("x:")).unwrap_or(false) {
        format!("{drive}{}", &name[2..])
    } else {
        name.to_string()
    }
}

fn replace_all(data: &[u8], from: &[u8], to: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(data.len());
    let mut i = 0;
    while i < data.len() {
        if data[i..].starts_with(from) {
            out.extend_from_slice(to);
            i += from.len();
        } else {
            out.push(data[i]);
            i += 1;
        }
    }
    out
}

fn fix_drive(typ: u32, data: &[u8], drive: &str) -> Vec<u8> {
    if matches!(typ, 1 | 2 | 7) {
        let to: Vec<u8> = drive.encode_utf16().flat_map(|c| c.to_le_bytes()).collect();
        let d = replace_all(data, &[b'X', 0, b':', 0], &to);
        replace_all(&d, &[b'x', 0, b':', 0], &to)
    } else {
        data.to_vec()
    }
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum DeviceReset {
    /// only when the device state is damaged
    Auto,
    Always,
    Never,
}

/// A user profile folder found on the disk.
#[derive(Clone, Debug)]
pub struct Profile {
    /// "C:\Users\admin" as the installation sees it
    pub path: String,
    /// binary SID of the account, from the SDs inside its NTUSER.DAT
    pub sid: Vec<u8>,
    /// folder creation time (any monotonic unit), oldest = original profile
    pub created: u64,
}

pub fn sid_string(b: &[u8]) -> String {
    if b.len() < 8 {
        return String::new();
    }
    let auth = b[2..8].iter().fold(0u64, |a, &x| (a << 8) | x as u64);
    let n = b[1] as usize;
    let subs: Vec<String> = (0..n).filter_map(|i| b.get(8 + 4 * i..12 + 4 * i))
        .map(|c| u32::from_le_bytes(c.try_into().unwrap()).to_string()).collect();
    format!("S-{}-{auth}-{}", b[0], subs.join("-"))
}

/// The account SID of a user hive: the most frequent user SID (S-1-5-21-…-RID ≥ 1000 or
/// Entra ID S-1-12-1-…) in its security descriptors.
pub fn user_hive_sid(d: &[u8]) -> Option<Vec<u8>> {
    let mut count: HashMap<Vec<u8>, usize> = HashMap::new();
    let mut i = 0;
    while i + 12 <= d.len() {
        let n = d[i + 1] as usize;
        let ok = d[i] == 1 && ((n == 5 && d[i + 2..i + 8] == [0, 0, 0, 0, 0, 5] && d[i + 8..i + 12] == [21, 0, 0, 0])
                               || (n == 5 && d[i + 2..i + 8] == [0, 0, 0, 0, 0, 12] && d[i + 8..i + 12] == [1, 0, 0, 0]));
        if ok && i + 8 + 4 * n <= d.len() {
            let sid = &d[i..i + 8 + 4 * n];
            let rid = u32::from_le_bytes(sid[sid.len() - 4..].try_into().unwrap());
            if d[i + 7] == 12 || rid >= 1000 {
                *count.entry(sid.to_vec()).or_default() += 1;
            }
            i += 8 + 4 * n;
        } else {
            i += 1;
        }
    }
    count.into_iter().max_by_key(|(_, c)| *c).map(|(s, _)| s)
}

pub struct Options {
    /// drive letter the installation calls itself ("C:")
    pub drive: String,
    /// installed CBS packages (lowercase .mum names without extension), SOFTWARE only
    pub installed_mums: Option<HashSet<String>>,
    pub device_reset: DeviceReset,
    /// user profile folders on the disk (SOFTWARE: ProfileList rule)
    pub profiles: Vec<Profile>,
    /// registered package manifests (AppRepository\<full name>.xml): (full name, xml)
    pub app_manifests: Vec<(String, String)>,
    /// does this path (as the installation sees it, "C:\…") exist on the disk?
    pub exists: Option<std::sync::Arc<dyn Fn(&str) -> bool + Send + Sync>>,
}

#[derive(Default, Debug)]
pub struct Report {
    /// (kind, path, detail)
    pub log: Vec<(String, String, String)>,
    pub undeleted: usize,
    pub keys_from_wim: usize,
    pub values_from_wim: usize,
    pub lost_state: Vec<String>,
    pub hw_profile: Option<u32>,
    pub driver_keys_rebuilt: usize,
    pub devices_reinstall: usize,
    pub device_reset: bool,
    pub classes_from_logs: usize,
    pub profiles_fixed: usize,
    pub appx_entries: usize,
    pub capauthz_entries: usize,
    pub computer_name: Option<String>,
}

impl Report {
    pub fn actions(&self) -> usize {
        self.undeleted + self.keys_from_wim + self.values_from_wim + self.lost_state.len()
            + self.hw_profile.is_some() as usize + self.driver_keys_rebuilt + self.devices_reinstall
            + self.device_reset as usize + self.classes_from_logs + self.profiles_fixed
            + self.computer_name.is_some() as usize + self.appx_entries + self.capauthz_entries
    }
    fn add(&mut self, kind: &str, path: &str, detail: &str) {
        self.log.push((kind.into(), path.into(), detail.into()));
    }
}

struct Repair<'a> {
    wim: &'a Key,
    opts: &'a Options,
    cs_map: Option<(String, String)>, // (vm current, wim current)
    rep: Report,
}

fn split(path: &str) -> Vec<&str> {
    path.split('\\').filter(|p| !p.is_empty()).collect()
}

impl<'a> Repair<'a> {
    fn wim_path(&self, path: &str) -> String {
        if let Some((vcs, wcs)) = &self.cs_map {
            let p = path.trim_start_matches('\\');
            if lower(p).starts_with(&lower(vcs)) {
                return format!("{wcs}{}", &p[vcs.len()..]);
            }
        }
        path.to_string()
    }

    // -- 2. undelete --------------------------------------------------------------
    /// Windows clears the security pointer of deleted keys, so the descriptor comes from
    /// the same key in the WIM, or else from the parent (what inheritance gives).
    fn undelete(&mut self, vm: &mut Key, deleted: &HashMap<String, Deleted>) {
        let mut order: Vec<&String> = deleted.keys().collect();
        order.sort_by_key(|k| (k.matches('\\').count(), (*k).clone()));
        for low in order {
            if NO_UNDELETE.iter().any(|x| low.contains(x)) {
                continue;
            }
            let d = &deleted[low];
            let parts = split(&d.path);
            let Some((last, parent_parts)) = parts.split_last() else { continue };
            let wim_sd = self.wim.get(&self.wim_path(&d.path)).map(|k| k.sd.clone());
            let Some(parent) = vm.get_mut(&parent_parts.join("\\")) else { continue };
            if let Some(existing) = parent.subs.get_mut(&lower(last)) {
                if existing.from_wim {
                    // created from the WIM in this run: the machine's own copy wins
                    let names: HashSet<String> = d.values.iter().map(|v| lower(&v.name)).collect();
                    let mut vals = d.values.clone();
                    vals.extend(existing.values.drain(..).filter(|v| !names.contains(&lower(&v.name))));
                    existing.values = vals;
                    if d.class.is_some() {
                        existing.class = d.class.clone();
                    }
                    existing.from_wim = false;
                    self.rep.add("undeleted over wim", &d.path, if d.class.is_some() { "class" } else { "" });
                }
                continue;
            }
            let sd = d.sd.clone().or(wim_sd).unwrap_or_else(|| parent.sd.clone());
            parent.subs.insert(lower(last), Key {
                name: last.to_string(), flags: d.flags & !0x2C, ts: d.ts_bytes, access: d.access,
                class: d.class.clone(), sd, values: d.values.clone(), restored: true, ..Default::default()
            });
            self.rep.undeleted += 1;
            self.rep.add("undeleted", &d.path, if d.class.is_some() { "class" } else { "" });
        }
    }

    // -- 3. lost state databases -----------------------------------------------------
    fn restore_lost_state(&mut self, vm: &mut Key) {
        let wim = self.wim;
        for sk in RESTORABLE_STATE {
            let Some(w) = wim.get(sk) else { continue };
            let have = vm.get(sk).map(|v| v.count()).unwrap_or(0);
            if have as f64 > w.count() as f64 * (1.0 - STATE_LOSS) {
                continue;
            }
            self.rep.lost_state.push(format!("{sk} ({have}/{} keys)", w.count()));
            let parts = split(sk);
            let (last, pp) = parts.split_last().unwrap();
            let Some(parent) = vm.get_mut(&pp.join("\\")) else { continue };
            if !parent.subs.contains_key(*last) {
                parent.subs.insert(last.to_string(), Key::new_like(&w.name, w));
                self.rep.keys_from_wim += 1;
                self.rep.add("key", sk, "");
            }
            let v = parent.subs.get_mut(*last).unwrap();
            self.copy_into(w, v, sk, true);
        }
    }

    // -- 4. WIM merge ---------------------------------------------------------------
    fn copy_values(&mut self, w: &Key, v: &mut Key, path: &str, state_ok: bool) {
        let have: HashSet<String> = v.values.iter().map(|x| lower(&fix_name(&x.name, &self.opts.drive))).collect();
        for x in &w.values {
            let n = fix_name(&x.name, &self.opts.drive);
            if have.contains(&lower(&n)) || (!state_ok && is_state(path, Some(&n))) {
                continue;
            }
            v.values.push(Value { name: n.clone(), typ: x.typ, data: fix_drive(x.typ, &x.data, &self.opts.drive) });
            self.rep.values_from_wim += 1;
            self.rep.add("value", path, &n);
        }
    }

    fn copy_into(&mut self, w: &Key, v: &mut Key, path: &str, state_ok: bool) {
        if !state_ok && is_state(path, None) {
            return;
        }
        self.copy_values(w, v, path, state_ok);
        let cbs = lower(path) == CBS_PACKAGES;
        for (low, wc) in &w.subs {
            let sub = format!("{path}\\{}", wc.name);
            if cbs {
                if let Some(m) = &self.opts.installed_mums {
                    if !m.contains(low) {
                        self.rep.add("skipped removed package", &sub, "");
                        continue;
                    }
                }
            }
            if !state_ok && is_state(&sub, None) {
                continue;
            }
            if !v.subs.contains_key(low) {
                let mut k = Key::new_like(&wc.name, wc);
                k.from_wim = true;
                v.subs.insert(low.clone(), k);
                self.rep.keys_from_wim += 1;
                self.rep.add("key", &sub, "");
            }
            let vc = v.subs.get_mut(low).unwrap();
            self.copy_into(wc, vc, &sub, state_ok);
        }
    }

    fn merge(&mut self, vm: &mut Key) {
        let wim = self.wim;
        if let Some((vcs, wcs)) = self.cs_map.clone() {
            // SYSTEM: map the current control set on both sides
            if let (Some(w), Some(v)) = (wim.get(&wcs), vm.get_mut(&vcs)) {
                self.copy_into(w, v, "CurrentControlSet", false);
            }
            for (low, wc) in &wim.subs {
                if low.starts_with("controlset") {
                    continue;
                }
                if !vm.subs.contains_key(low) {
                    if is_state(&wc.name, None) {
                        continue;
                    }
                    vm.subs.insert(low.clone(), Key::new_like(&wc.name, wc));
                    self.rep.keys_from_wim += 1;
                    self.rep.add("key", &wc.name, "");
                }
                let vc = vm.subs.get_mut(low).unwrap();
                self.copy_into(wc, vc, &wc.name.clone(), false);
            }
        } else {
            self.copy_into(wim, vm, "", false);
        }
    }

    // -- 5. SYSTEM: devices --------------------------------------------------------
    /// The WIM's Control\IDConfigDB is the pre-setup template (CurrentConfig 0, only the
    /// "Pristine" profile 0000). Setup clones it into profile 0001+; with the template the
    /// boot loader stops with 0xc0000001. Rebuild it from <CS>\Hardware Profiles.
    fn fix_hwprofile(&mut self, cs: &mut Key) {
        let nums: Vec<u32> = cs.get("Hardware Profiles").map(|p| {
            p.subs.keys().filter_map(|n| n.parse::<u32>().ok()).filter(|&n| n > 0).collect()
        }).unwrap_or_default();
        let Some(idc) = cs.get_mut(r"Control\IDConfigDB") else { return };
        let cur = idc.dword("CurrentConfig").unwrap_or(0);
        if cur != 0 && idc.get(&format!(r"Hardware Profiles\{cur:04}")).is_some() {
            return; // intact
        }
        let Some(&n) = nums.iter().max() else { return };
        let dword = |x: u32| x.to_le_bytes().to_vec();
        if idc.get("Hardware Profiles").is_none() {
            let k = Key::new_like("Hardware Profiles", idc);
            idc.subs.insert("hardware profiles".into(), k);
        }
        let hp = idc.get_mut("Hardware Profiles").unwrap();
        hp.set_value("Undocked", 4, dword(n));
        let pn = format!("{n:04}");
        if !hp.subs.contains_key(&pn) {
            let k = Key::new_like(&pn, hp);
            hp.subs.insert(pn.clone(), k);
        }
        let p = hp.subs.get_mut(&pn).unwrap();
        for (name, typ, data) in [
            ("PreferenceOrder", 4, dword(0)), ("FriendlyName", 1, utf16z("Undocked Profile")),
            ("Aliasable", 4, dword(0)), ("Cloned", 4, dword(1)), ("HwProfileGuid", 1, utf16z(&new_guid())),
        ] {
            if p.value(name).is_none() {
                p.set_value(name, typ, data);
            }
        }
        if idc.get("AcpiAlias").is_none() {
            let mut alias = Key::new_like("AcpiAlias", idc);
            let mut a = Key::new_like("0001", &alias);
            a.values = vec![
                Value { name: "DockingState".into(), typ: 4, data: dword(1) },
                Value { name: "AcpiSerialNumber".into(), typ: 3, data: vec![0, 0] },
                Value { name: "ProfileNumber".into(), typ: 4, data: dword(n) },
            ];
            alias.subs.insert("0001".into(), a);
            idc.subs.insert("acpialias".into(), alias);
        }
        idc.set_value("CurrentConfig", 4, dword(n));
        self.rep.hw_profile = Some(n);
        self.rep.add("hardware profile", r"Control\IDConfigDB", &pn);
    }

    /// Devices whose Control\Class\{guid}\NNNN driver key is gone (Enum path, driver).
    fn devices_without_driver_key(cs: &Key) -> Vec<(String, String)> {
        let mut out = Vec::new();
        let classes = cs.get(r"Control\Class");
        if let Some(e) = cs.get("Enum") {
            for (en, a) in &e.subs {
                for (bn, b) in &a.subs {
                    for (dn, dev) in &b.subs {
                        let Some(drv) = dev.string("Driver") else { continue };
                        let (guid, inst) = drv.split_once('\\').unwrap_or((&drv, ""));
                        let ok = classes.and_then(|c| c.subs.get(&lower(guid)))
                            .map(|c| c.subs.contains_key(&lower(inst))).unwrap_or(false);
                        if !ok {
                            out.push((format!("Enum\\{en}\\{bn}\\{dn}"), drv));
                        }
                    }
                }
            }
        }
        out.sort();
        out
    }

    /// 1. Rebuild the driver key from the device's own driver properties
    ///    (Enum\…\Properties\{a8b865dd…}) — enough for the kernel to start it normally.
    /// 2. CONFIGFLAG_REINSTALL only when that's impossible or the class keeps more there
    ///    (network), and never for boot/system-start drivers: PnP can't install those before
    ///    the boot disk is up (IO1_INITIALIZATION_FAILED / INACCESSIBLE_BOOT_DEVICE).
    fn fix_devices(&mut self, cs: &mut Key) {
        for (path, drv) in Self::devices_without_driver_key(cs) {
            let (guid, inst) = drv.split_once('\\').unwrap_or((&drv, ""));
            let (guid, inst) = (guid.to_string(), inst.to_string());
            let dev = cs.get(&path).unwrap();
            let svc = dev.string("Service").unwrap_or_default();
            let start = if svc.is_empty() { None } else { cs.get(&format!(r"Services\{svc}")).and_then(|s| s.dword("Start")) };
            let dk = driver_key_from_props(dev.get(&format!(r"Properties\{DRIVER_PROPS}")));
            let mut rebuilt = false;
            if let (Some(vals), Some(class)) = (dk, cs.get_mut(&format!(r"Control\Class\{guid}"))) {
                let mut k = Key::new_like(&inst, class);
                k.values = vals;
                class.subs.insert(lower(&inst), k);
                self.rep.driver_keys_rebuilt += 1;
                self.rep.add("driver key from properties", &path, &drv);
                rebuilt = true;
            }
            if matches!(start, Some(s) if s <= 1) {
                continue;
            }
            if rebuilt && !REINSTALL_CLASSES.contains(&lower(&guid).as_str()) {
                continue;
            }
            let dev = cs.get_mut(&path).unwrap();
            let old = dev.dword("ConfigFlags").unwrap_or(0);
            dev.set_value("ConfigFlags", 4, (old | CONFIGFLAG_REINSTALL).to_le_bytes().to_vec());
            self.rep.devices_reinstall += 1;
            self.rep.add("pnp reinstall", &path, &drv);
        }
    }

    /// Clean device start: PnP device state from the (generalized) WIM, so Windows
    /// detects all hardware again on first boot. Also the WIM's start type for every
    /// service that is boot-start there.
    fn reset_devices(&mut self, cs: &mut Key) {
        let wim = self.wim;
        let Some(wcs) = self.cs_map.as_ref().and_then(|(_, w)| wim.get(w)) else { return };
        if let Some(e) = wcs.get("Enum") {
            cs.subs.insert("enum".into(), e.clone());
        }
        let wc = wcs.get("Control");
        if let Some(vc) = cs.get_mut("Control") {
            for name in ["deviceclasses", "devicecontainers"] {
                match wc.and_then(|w| w.subs.get(name)) {
                    Some(k) => { vc.subs.insert(name.into(), k.clone()); }
                    None => { vc.subs.remove(name); }
                }
            }
            if let Some(vclass) = vc.subs.get_mut("class") {
                let wclass = wc.and_then(|w| w.get("Class"));
                for (low, k) in vclass.subs.iter_mut() {
                    k.subs.retain(|n, _| !n.chars().all(|c| c.is_ascii_digit()));
                    if let Some(w) = wclass.and_then(|c| c.subs.get(low)) {
                        for (n, ik) in &w.subs {
                            if n.chars().all(|c| c.is_ascii_digit()) {
                                k.subs.insert(n.clone(), ik.clone());
                            }
                        }
                    }
                }
            }
        }
        let mut n = 0;
        if let (Some(ws), Some(vs)) = (wcs.get("Services"), cs.subs.get_mut("services")) {
            for (low, w) in &ws.subs {
                let Some(start) = w.value("Start") else { continue };
                if w.dword("Start") != Some(0) {
                    continue;
                }
                if let Some(v) = vs.subs.get_mut(low) {
                    v.set_value("Start", start.typ, start.data.clone());
                    n += 1;
                }
            }
        }
        self.rep.device_reset = true;
        self.rep.add("clean device start", "Enum, DeviceClasses, DeviceContainers, Class instances",
                     &format!("{n} boot-start services"));
    }
}

const PROFILE_LIST: &str = r"Microsoft\Windows NT\CurrentVersion\ProfileList";

/// Accounts whose ProfileList entry is gone get it back; without it Windows logs the user
/// on with a new, empty profile ("user.COMPUTER", Start menu and apps broken). If Windows
/// already made such a duplicate, the entry is pointed back to the oldest folder.
fn fix_profiles(vm: &mut Key, profiles: &[Profile], rep: &mut Report) {
    let Some(pl) = vm.get_mut(PROFILE_LIST) else { return };
    let mut by_sid: HashMap<String, &Profile> = HashMap::new();
    for p in profiles {
        let s = sid_string(&p.sid);
        if by_sid.get(&s).map(|q| p.created < q.created).unwrap_or(true) {
            by_sid.insert(s, p);
        }
    }
    let mut sids: Vec<_> = by_sid.into_iter().collect();
    sids.sort_by(|a, b| a.0.cmp(&b.0));
    for (sid, p) in sids {
        let low = lower(&sid);
        match pl.subs.get_mut(&low) {
            None => {
                let mut k = Key::new_like(&sid, pl);
                for (n, t, d) in [
                    ("ProfileImagePath", 2, utf16z(&p.path)), ("Flags", 4, 0u32.to_le_bytes().to_vec()),
                    ("State", 4, 0u32.to_le_bytes().to_vec()), ("FullProfile", 4, 1u32.to_le_bytes().to_vec()),
                    ("Sid", 3, p.sid.clone()),
                ] {
                    k.set_value(n, t, d);
                }
                pl.subs.insert(low, k);
                rep.profiles_fixed += 1;
                rep.add("profile entry rebuilt", &sid, &p.path);
            }
            Some(k) => {
                let cur = k.string("ProfileImagePath").unwrap_or_default();
                if !cur.eq_ignore_ascii_case(&p.path) && profiles.iter().any(|q| q.path.eq_ignore_ascii_case(&cur)) {
                    k.set_value("ProfileImagePath", 2, utf16z(&p.path));
                    k.set_value("State", 4, 0u32.to_le_bytes().to_vec());
                    rep.profiles_fixed += 1;
                    rep.add("profile entry pointed back", &sid, &format!("{cur} -> {}", p.path));
                }
            }
        }
    }
}

const APPX_STORE: &str = r"Microsoft\Windows\CurrentVersion\Appx\AppxAllUserStore";

/// Per-user AppX bookkeeping: AppxAllUserStore\<SID>\<package> exists for every inbox
/// (InboxApplications) and provisioned (Applications) package the user has. When a big part
/// of a user's list is gone, Start menu, Settings and other apps stop working ("Die Anwendung
/// wurde nicht bereitgestellt"). Rebuilt from the source keys; only on clear damage, so a
/// package the user removed on purpose doesn't come back.
fn fix_appx_users(vm: &mut Key, opts: &Options, rep: &mut Report) {
    let Some(store) = vm.get_mut(APPX_STORE) else { return };
    let mut sources: Vec<Key> = Vec::new();
    for s in ["inboxapplications", "applications"] {
        if let Some(k) = store.subs.get(s) {
            sources.extend(k.subs.values().cloned());
        }
    }
    let deprovisioned: HashSet<String> = store.subs.get("deprovisioned")
        .map(|k| k.subs.keys().cloned().collect()).unwrap_or_default();
    // packages are named <Name>_<Version>_<Arch>_<ResourceId>_<PublisherId>; deprovisioned by family
    let family = |n: &str| {
        let p: Vec<&str> = n.split('_').collect();
        if p.len() >= 5 { format!("{}_{}", p[0], p[p.len() - 1]) } else { n.to_string() }
    };
    let deprov_families: HashSet<String> = deprovisioned.iter().map(|d| family(d)).collect();
    for (low, user) in store.subs.iter_mut() {
        if !(low.starts_with("s-1-5-21-") || low.starts_with("s-1-12-")) {
            continue;
        }
        let expected: Vec<&Key> = sources.iter()
            .filter(|k| !deprov_families.contains(&family(&lower(&k.name)))).collect();
        let missing: Vec<&Key> = expected.iter().copied().filter(|k| !user.subs.contains_key(&lower(&k.name))).collect();
        if missing.len() < 5 || missing.len() * 10 < expected.len() {
            continue;
        }
        for src in missing {
            if let (Some(ex), Some(p)) = (&opts.exists, src.string("Path")) {
                if !ex(&p) {
                    rep.add("appx user entry skipped, package files gone", &user.name.clone(), &src.name);
                    continue;
                }
            }
            let mut k = src.clone();
            k.restored = true;
            k.set_value("LastReturnValue", 4, 0u32.to_le_bytes().to_vec());
            k.set_value("NumberOfAttempts", 4, 1u32.to_le_bytes().to_vec());
            user.subs.insert(lower(&k.name), k);
            rep.appx_entries += 1;
            rep.add("appx user entry rebuilt", &user.name.clone(), &src.name);
        }
    }
}

const CAPAUTHZ: &str = r"Microsoft\SecurityManager\CapAuthz\ApplicationsEx";

/// Capability entries of packaged apps (see capauthz.rs). Only on clear damage.
fn fix_capauthz(vm: &mut Key, opts: &Options, rep: &mut Report) {
    let main: Vec<&(String, String)> = opts.app_manifests.iter()
        .filter(|(n, _)| super::capauthz::is_main_package(n)).collect();
    if main.is_empty() {
        return;
    }
    let devmap = super::capauthz::device_map(vm);
    if vm.get(CAPAUTHZ).is_none() {
        let Some(parent) = vm.get_mut(r"Microsoft\SecurityManager\CapAuthz") else { return };
        let k = Key::new_like("ApplicationsEx", parent);
        parent.subs.insert("applicationsex".into(), k);
    }
    let ax = vm.get_mut(CAPAUTHZ).unwrap();
    let missing: Vec<&&(String, String)> = main.iter().filter(|(n, _)| !ax.subs.contains_key(&lower(n))).collect();
    if missing.len() < 5 || missing.len() * 10 < main.len() {
        return;
    }
    for (name, xml) in missing {
        let mut k = Key::new_like(name, ax);
        for (n, t, d) in super::capauthz::entry(name, xml, &devmap) {
            k.set_value(&n, t, d);
        }
        ax.subs.insert(lower(name), k);
        rep.capauthz_entries += 1;
        rep.add("app capabilities rebuilt", CAPAUTHZ, name);
    }
}

/// ComputerName restored from the WIM is its placeholder; the real name survives as the
/// TCP/IP host name.
fn fix_computer_name(cs: &mut Key, wim_cs: Option<&Key>, rep: &mut Report) {
    let placeholder = wim_cs.and_then(|w| w.get(r"Control\ComputerName\ComputerName"))
        .and_then(|k| k.string("ComputerName")).unwrap_or_else(|| "MINWINPC".into());
    let Some(host) = cs.get(r"Services\Tcpip\Parameters").and_then(|k| k.string("Hostname").or_else(|| k.string("NV Hostname"))) else { return };
    if host.is_empty() {
        return;
    }
    let Some(k) = cs.get_mut(r"Control\ComputerName\ComputerName") else { return };
    let cur = k.string("ComputerName").unwrap_or_default();
    if !cur.is_empty() && !cur.eq_ignore_ascii_case(&placeholder) {
        return;
    }
    let name: String = host.to_uppercase().chars().take(15).collect();
    if name.eq_ignore_ascii_case(&cur) {
        return;
    }
    k.set_value("ComputerName", 1, utf16z(&name));
    rep.computer_name = Some(name.clone());
    rep.add("computer name", r"Control\ComputerName\ComputerName", &format!("{cur} -> {name}"));
}

fn new_guid() -> String {
    use std::hash::{BuildHasher, Hasher};
    let mut b = [0u8; 16];
    for (i, ch) in b.chunks_mut(8).enumerate() {
        let mut h = std::collections::hash_map::RandomState::new().build_hasher();
        h.write_usize(i);
        h.write_u128(std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_nanos()).unwrap_or(0));
        ch.copy_from_slice(&h.finish().to_le_bytes());
    }
    b[6] = (b[6] & 0x0F) | 0x40;
    b[8] = (b[8] & 0x3F) | 0x80;
    format!("{{{:08x}-{:04x}-{:04x}-{:04x}-{:012x}}}",
            u32::from_be_bytes(b[0..4].try_into().unwrap()), u16::from_be_bytes([b[4], b[5]]),
            u16::from_be_bytes([b[6], b[7]]), u16::from_be_bytes([b[8], b[9]]),
            u64::from_be_bytes([0, 0, b[10], b[11], b[12], b[13], b[14], b[15]]))
}

/// Values of a device's driver key, rebuilt from Enum\…\Properties\{a8b865dd…}.
fn driver_key_from_props(props: Option<&Key>) -> Option<Vec<Value>> {
    let props = props?;
    let raw: HashMap<String, &Vec<u8>> = props.subs.iter()
        .filter_map(|(pid, k)| k.values.iter().find(|v| v.name.is_empty()).map(|v| (pid.to_uppercase(), &v.data)))
        .collect();
    if !raw.contains_key("0005") || !raw.contains_key("0004") {
        return None;
    }
    let mut out = Vec::new();
    for (pid, name) in [("0004", "DriverDesc"), ("0009", "ProviderName"), ("0002", "DriverDateData"),
                        ("0002", "DriverDate"), ("0003", "DriverVersion"), ("0005", "InfPath"),
                        ("0006", "InfSection"), ("0008", "MatchingDeviceId")] {
        let Some(d) = raw.get(pid) else { continue };
        let (typ, data) = match name {
            "DriverDateData" => (3, d[..d.len().min(8)].to_vec()),
            "DriverDate" => {
                let ft = u64::from_le_bytes(d.get(..8)?.try_into().ok()?);
                let (y, m, day) = civil_from_days((ft / 10_000_000 / 86_400) as i64 - 134_774);
                (1, utf16z(&format!("{m}-{day}-{y}")))
            }
            _ => (1, (*d).clone()),
        };
        out.push(Value { name: name.into(), typ, data });
    }
    Some(out)
}

/// days since 1970-01-01 -> (year, month, day)
fn civil_from_days(z: i64) -> (i64, u32, u32) {
    let z = z + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    (yoe + era * 400 + (m <= 2) as i64, m, d)
}

/// Repair `vm` (already log-replayed, `vm_bytes` = its file for free-cell recovery) against
/// the same hive from the WIM. `logs` = the original .LOG1/.LOG2 (stale nk records).
pub fn repair(vm: &mut Key, vm_bytes: &[u8], logs: &[&[u8]], wim: &Key, opts: &Options) -> Report {
    let system = wim.get("Select").is_some();
    let cs_map = if system {
        match (vm.current_control_set(), wim.current_control_set()) {
            (Some(v), Some(w)) => Some((v, w)),
            _ => None,
        }
    } else {
        None
    };
    let mut r = Repair { wim, opts, cs_map, rep: Report::default() };

    let fc = FreeCells::new(vm_bytes);
    // Windows deletes keys itself all the time; only bring deleted keys back when the hive
    // is damaged (keys the WIM has are missing), else a healthy hive would get changes.
    let damaged = {
        let mut probe = Repair { wim, opts, cs_map: r.cs_map.clone(), rep: Report::default() };
        let mut copy = vm.clone();
        probe.merge(&mut copy);
        probe.rep.keys_from_wim > 0
    };
    let deleted = if damaged { fc.deleted_keys() } else { HashMap::new() };
    r.undelete(vm, &deleted);
    if !system {
        r.restore_lost_state(vm);
    }
    r.merge(vm);
    r.undelete(vm, &deleted); // 2nd pass: parents that only came back from the WIM

    if !system {
        fix_profiles(vm, &opts.profiles, &mut r.rep);
        fix_appx_users(vm, opts, &mut r.rep);
        fix_capauthz(vm, opts, &mut r.rep);
    }
    if let Some((vcs, wcs)) = r.cs_map.clone() {
        if let Some(cs) = vm.get_mut(&vcs) {
            fix_computer_name(cs, wim.get(&wcs), &mut r.rep);
            r.fix_hwprofile(cs);
            let damaged = Repair::devices_without_driver_key(cs).len();
            let reset = match opts.device_reset {
                DeviceReset::Always => true,
                DeviceReset::Never => false,
                DeviceReset::Auto => damaged > 0,
            };
            if reset {
                if damaged > 0 {
                    r.rep.add("device state damaged", "Control\\Class", &format!("{damaged} devices without driver key"));
                }
                r.reset_devices(cs);
            } else {
                r.fix_devices(cs);
            }
        }
    }

    // class names for restored keys that came back without one (e.g. Lsa boot key)
    for (path, cls) in fc.classes_from_logs(logs) {
        if let Some(k) = vm.get_mut(&path) {
            if k.restored && k.class.as_ref() != Some(&cls) {
                k.class = Some(cls.clone());
                r.rep.classes_from_logs += 1;
                let w: Vec<u16> = cls.chunks_exact(2).map(|c| u16::from_le_bytes([c[0], c[1]])).collect();
                r.rep.add("class from log", &path, &String::from_utf16_lossy(&w));
            }
        }
    }
    r.rep
}
