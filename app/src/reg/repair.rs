//! Registry repair rules. Port of proto/regrepair2.py + proto/regdiff.py + proto/devreset.py.
//!
//! Order:
//!   1. (caller) replay transaction logs
//!   2. undelete intact keys from free cells (the machine's own data, best source)
//!   3. restore lost state databases from the WIM (SOFTWARE)
//!   4. add keys/values missing compared to the WIM (X: -> install drive)
//!   5. SYSTEM: hardware profile, device driver keys or clean device start
//!   6. class names for restored keys from stale log records (Lsa boot key)
//!   7. (caller) write a fresh compact hive

